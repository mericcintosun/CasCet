"""
Cross-implementation vectors: the Python client must reproduce, byte for byte,
what the TypeScript stack computes. eip712_vectors.json was generated by running
@casper-ecosystem/casper-eip-712, @make-software/casper-x402, casper-js-sdk and
@x402/core 2.17 from this repo's node_modules, x402_casper_2_29_vectors.json by
running the @x402 2.29 stack (@x402/core, @x402/casper, @cascet/client's scheme
wrapper and signer); see each file's `generator` field.
"""
import json
import unittest
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from helpers import TEST_KEY, VECTORS, x402

#: Vectors from the @x402 2.29 TypeScript stack (both authorization styles).
VECTORS_2_29 = json.loads((Path(__file__).parent / "x402_casper_2_29_vectors.json").read_text("utf-8"))

#: DESIGN section 8 of the 2.29 migration: one TransferWithAuthorization (from
#: 0065190126...faf9 to the demo seller, value 500000000, validAfter 0,
#: validBefore 1893456000, nonce 0x11 x 32) under each token's EIP-712 domain.
DESIGN_SECTION_8_DIGESTS = {
    "legacy-amount": "fa7f8fb8a4baf5f10c417995ed89ef3e4a187827d0b390da72ea6fc8473c019f",  # CasCet X402 Token
    "cep3009-value": "7018efb474af3db4090555b34126928be63ef25e57af57c3be95050bb210ca55",  # Wrapped CSPR
}


class TestKeyVectors(unittest.TestCase):
    def test_test_key_matches_casper_js_sdk(self):
        key = VECTORS["key"]
        self.assertEqual(TEST_KEY.public_key_hex(), key["publicKeyHex"])
        self.assertEqual(TEST_KEY.account_hash_hex(), key["accountHashHex"])
        self.assertEqual(TEST_KEY.account_address(), key["accountAddress"])

    def test_account_hash_from_public_key(self):
        for case in VECTORS["accountHashes"]:
            with self.subTest(public_key=case["publicKeyHex"]):
                self.assertEqual(x402.account_hash_from_public_key(case["publicKeyHex"]), case["accountHashHex"])
                self.assertEqual(x402.pay_to_from_public_key(case["publicKeyHex"]), "00" + case["accountHashHex"])


class TestEip712DigestVectors(unittest.TestCase):
    def test_domain_separator_struct_hash_and_digest(self):
        self.assertGreaterEqual(len(VECTORS["digests"]), 5)
        for case in VECTORS["digests"]:
            domain, msg = case["domain"], case["message"]
            with self.subTest(case=case["name"]):
                self.assertEqual(
                    x402._hash_domain(domain["name"], domain["version"], domain["network"], "0x" + domain["asset"]).hex(),
                    case["domainSeparatorHex"],
                )
                self.assertEqual(
                    x402._hash_struct(
                        msg["from"], msg["to"], int(msg["value"]), int(msg["validAfter"]), int(msg["validBefore"]),
                        msg["nonce"],
                    ).hex(),
                    case["structHashHex"],
                )
                digest = x402.transfer_with_auth_digest(
                    name=domain["name"], version=domain["version"], chain_name=domain["network"],
                    asset=domain["asset"], frm=msg["from"], to=msg["to"], value=int(msg["value"]),
                    valid_after=int(msg["validAfter"]), valid_before=int(msg["validBefore"]), nonce_hex=msg["nonce"],
                )
                self.assertEqual(digest.hex(), case["digestHex"])


class TestPaymentPayloadVector(unittest.TestCase):
    """The full payload the TS x402Client + ExactCasperScheme built for a fixed time and nonce."""

    def setUp(self):
        self.vector = VECTORS["payment"]
        self.payment_required = self.vector["paymentRequired"]
        self.payload = x402.build_payment_payload(
            key=TEST_KEY,
            requirements=self.payment_required["accepts"][0],
            resource=self.payment_required["resource"],
            nonce=bytes.fromhex(self.vector["nonceHex"]),
            now=self.vector["now"],
        )

    def test_payload_equals_typescript_payload(self):
        self.assertEqual(self.payload, self.vector["paymentPayload"])

    def test_payment_signature_header_is_byte_identical(self):
        self.assertEqual(x402.payment_signature_header(self.payload), self.vector["paymentSignatureHeader"])

    def test_signature_is_over_the_vector_digest(self):
        auth = self.payload["payload"]["authorization"]
        req = self.payment_required["accepts"][0]
        digest = x402.transfer_with_auth_digest(
            name=req["extra"]["name"], version=req["extra"]["version"], chain_name=req["network"], asset=req["asset"],
            frm="0x" + auth["from"], to="0x" + auth["to"], value=int(auth["value"]),
            valid_after=int(auth["validAfter"]), valid_before=int(auth["validBefore"]), nonce_hex=auth["nonce"],
        )
        self.assertEqual(digest.hex(), self.vector["digestHex"])
        signature = bytes.fromhex(self.payload["payload"]["signature"])
        self.assertEqual(len(signature), 65)
        self.assertEqual(signature[0], 0x01)  # ed25519 algorithm tag
        Ed25519PublicKey.from_public_bytes(TEST_KEY.public_key_bytes).verify(signature[1:], digest)  # raises if bad

    def test_payment_required_header_decodes(self):
        self.assertEqual(x402.decode_payment_required_header(self.vector["paymentRequiredHeader"]), self.payment_required)


class TestDesignDigestVectors(unittest.TestCase):
    """Both authorization styles sign the same message: only the token's EIP-712 domain differs."""

    def test_both_domains_match_the_typescript_digest(self):
        cases = VECTORS_2_29["digests"]
        self.assertEqual(sorted(case["authorizationStyle"] for case in cases), sorted(x402.AUTHORIZATION_STYLES))
        for case in cases:
            domain, msg = case["domain"], case["message"]
            with self.subTest(case=case["name"]):
                self.assertEqual(case["digestHex"], DESIGN_SECTION_8_DIGESTS[case["authorizationStyle"]])
                self.assertEqual(msg["validAfter"], "0")
                self.assertEqual(
                    x402._hash_domain(domain["name"], domain["version"], domain["network"], "0x" + domain["asset"]).hex(),
                    case["domainSeparatorHex"],
                )
                self.assertEqual(
                    x402._hash_struct(
                        msg["from"], msg["to"], int(msg["value"]), int(msg["validAfter"]), int(msg["validBefore"]),
                        msg["nonce"],
                    ).hex(),
                    case["structHashHex"],
                )
                digest = x402.transfer_with_auth_digest(
                    name=domain["name"], version=domain["version"], chain_name=domain["network"],
                    asset=domain["asset"], frm=msg["from"], to=msg["to"], value=int(msg["value"]),
                    valid_after=int(msg["validAfter"]), valid_before=int(msg["validBefore"]), nonce_hex=msg["nonce"],
                )
                self.assertEqual(digest.hex(), DESIGN_SECTION_8_DIGESTS[case["authorizationStyle"]])

    def test_the_message_is_the_same_for_both_styles(self):
        legacy, wcspr = sorted(VECTORS_2_29["digests"], key=lambda case: case["authorizationStyle"] != "legacy-amount")
        self.assertEqual(legacy["message"], wcspr["message"])
        self.assertEqual(legacy["structHashHex"], wcspr["structHashHex"])
        self.assertNotEqual(legacy["domainSeparatorHex"], wcspr["domainSeparatorHex"])
        # The CasCet token's domain is the one the 2.17-era vectors use too.
        self.assertEqual(legacy["domainSeparatorHex"], VECTORS["digests"][0]["domainSeparatorHex"])


class TestX402Casper229PaymentVectors(unittest.TestCase):
    """Payloads @x402/core 2.29 + @x402/casper 2.29 (the TypeScript client) built for a fixed time and nonce."""

    def setUp(self):
        self.vector = VECTORS_2_29["payment"]
        self.payment_required = self.vector["paymentRequired"]

    def build(self, requirements, **kwargs):
        return x402.build_payment_payload(
            key=TEST_KEY,
            requirements=requirements,
            resource=self.payment_required["resource"],
            nonce=bytes.fromhex(self.vector["nonceHex"]),
            now=self.vector["now"],
            **kwargs,
        )

    def test_the_vector_key_is_the_test_key(self):
        self.assertEqual(VECTORS_2_29["key"]["accountAddress"], TEST_KEY.account_address())

    def test_payloads_equal_the_typescript_payloads_with_valid_after_0(self):
        self.assertEqual(len(self.vector["payments"]), 2)
        for case in self.vector["payments"]:
            requirements = self.payment_required["accepts"][case["acceptsIndex"]]
            with self.subTest(case=case["name"]):
                payload = self.build(requirements, valid_after=0)
                self.assertEqual(payload, case["paymentPayload"])
                self.assertEqual(x402.payment_signature_header(payload), case["paymentSignatureHeader"])
                self.assertEqual(payload["accepted"]["extra"]["authorizationStyle"], requirements["extra"]["authorizationStyle"])

    def test_the_default_window_differs_only_in_valid_after(self):
        case = self.vector["payments"][1]
        payload = self.build(self.payment_required["accepts"][case["acceptsIndex"]])
        auth, expected = payload["payload"]["authorization"], case["paymentPayload"]["payload"]["authorization"]
        self.assertEqual(auth["validAfter"], str(self.vector["now"] - 600))
        self.assertEqual({k: v for k, v in auth.items() if k != "validAfter"},
                         {k: v for k, v in expected.items() if k != "validAfter"})

    def test_signatures_are_over_the_vector_digests(self):
        public_key = Ed25519PublicKey.from_public_bytes(TEST_KEY.public_key_bytes)
        for case in self.vector["payments"]:
            requirements = self.payment_required["accepts"][case["acceptsIndex"]]
            auth = case["paymentPayload"]["payload"]["authorization"]
            with self.subTest(case=case["name"]):
                digest = x402.transfer_with_auth_digest(
                    name=requirements["extra"]["name"], version=requirements["extra"]["version"],
                    chain_name=requirements["network"], asset=requirements["asset"],
                    frm="0x" + auth["from"], to="0x" + auth["to"], value=int(auth["value"]),
                    valid_after=int(auth["validAfter"]), valid_before=int(auth["validBefore"]), nonce_hex=auth["nonce"],
                )
                self.assertEqual(digest.hex(), case["digestHex"])
                signature = bytes.fromhex(case["paymentPayload"]["payload"]["signature"])
                self.assertEqual(signature[0], 0x01)
                public_key.verify(signature[1:], digest)  # raises if bad

    def test_payment_required_header_decodes(self):
        decoded = x402.decode_payment_required_header(self.vector["paymentRequiredHeader"])
        self.assertEqual(decoded, self.payment_required)
        self.assertEqual(x402._b64_json_encode(self.payment_required), self.vector["paymentRequiredHeader"])

    def test_select_requirement_picks_by_style(self):
        accepts = self.payment_required["accepts"]
        allowed = [requirements["asset"] for requirements in accepts]
        seller = [accepts[0]["payTo"]]
        self.assertIs(x402.select_requirement(accepts, allowed, seller), accepts[0])
        self.assertIs(x402.select_requirement(accepts, allowed, seller, prefer_styles=["cep3009-value"]), accepts[1])
        self.assertIs(x402.select_requirement(accepts, allowed, seller, prefer_styles=["legacy-amount"]), accepts[0])
        self.assertIs(x402.select_requirement(accepts, [accepts[1]["asset"]], seller), accepts[1])


class TestHeaderVectors(unittest.TestCase):
    def test_encoding_matches_x402_core(self):
        names = [case["name"] for case in VECTORS["headers"]]
        self.assertTrue(any("non-ASCII" in name for name in names))
        self.assertTrue(any("surrogate" in name for name in names))  # JSON.stringify escapes lone surrogates
        for case in VECTORS["headers"]:
            with self.subTest(case=case["name"]):
                self.assertEqual(x402.payment_signature_header(case["object"]), case["base64"])
                self.assertEqual(x402.decode_payment_signature_header(case["base64"]), case["object"])


