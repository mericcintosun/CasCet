"""
Cross-implementation vectors: the Python client must reproduce, byte for byte,
what the TypeScript stack computes (eip712_vectors.json was generated by running
@casper-ecosystem/casper-eip-712, @make-software/casper-x402, casper-js-sdk and
@x402/core from this repo's node_modules; see its `generator` field).
"""
import unittest

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey

from helpers import TEST_KEY, VECTORS, x402


class TestKeyVectors(unittest.TestCase):
    def test_test_key_matches_casper_js_sdk(self):
        key = VECTORS["key"]
        self.assertEqual(TEST_KEY.public_key_hex(), key["publicKeyHex"])
        self.assertEqual(TEST_KEY.account_hash_hex(), key["accountHashHex"])
        self.assertEqual(TEST_KEY.account_address(), key["accountAddress"])

    def test_account_hash_from_public_key(self):
        for case in VECTORS["accountHashes"]:
            with self.subTest(public_key=case["publicKeyHex"]):
                self.assertEqual(x402.account_hash_from_public_key(case["publicKeyHex"]), case["accountHashHex"])
                self.assertEqual(x402.pay_to_from_public_key(case["publicKeyHex"]), "00" + case["accountHashHex"])


class TestEip712DigestVectors(unittest.TestCase):
    def test_domain_separator_struct_hash_and_digest(self):
        self.assertGreaterEqual(len(VECTORS["digests"]), 5)
        for case in VECTORS["digests"]:
            domain, msg = case["domain"], case["message"]
            with self.subTest(case=case["name"]):
                self.assertEqual(
                    x402._hash_domain(domain["name"], domain["version"], domain["network"], "0x" + domain["asset"]).hex(),
                    case["domainSeparatorHex"],
                )
                self.assertEqual(
                    x402._hash_struct(
                        msg["from"], msg["to"], int(msg["value"]), int(msg["validAfter"]), int(msg["validBefore"]),
                        msg["nonce"],
                    ).hex(),
                    case["structHashHex"],
                )
                digest = x402.transfer_with_auth_digest(
                    name=domain["name"], version=domain["version"], chain_name=domain["network"],
                    asset=domain["asset"], frm=msg["from"], to=msg["to"], value=int(msg["value"]),
                    valid_after=int(msg["validAfter"]), valid_before=int(msg["validBefore"]), nonce_hex=msg["nonce"],
                )
                self.assertEqual(digest.hex(), case["digestHex"])


class TestPaymentPayloadVector(unittest.TestCase):
    """The full payload the TS x402Client + ExactCasperScheme built for a fixed time and nonce."""

    def setUp(self):
        self.vector = VECTORS["payment"]
        self.payment_required = self.vector["paymentRequired"]
        self.payload = x402.build_payment_payload(
            key=TEST_KEY,
            requirements=self.payment_required["accepts"][0],
            resource=self.payment_required["resource"],
            nonce=bytes.fromhex(self.vector["nonceHex"]),
            now=self.vector["now"],
        )

    def test_payload_equals_typescript_payload(self):
        self.assertEqual(self.payload, self.vector["paymentPayload"])

    def test_payment_signature_header_is_byte_identical(self):
        self.assertEqual(x402.payment_signature_header(self.payload), self.vector["paymentSignatureHeader"])

    def test_signature_is_over_the_vector_digest(self):
        auth = self.payload["payload"]["authorization"]
        req = self.payment_required["accepts"][0]
        digest = x402.transfer_with_auth_digest(
            name=req["extra"]["name"], version=req["extra"]["version"], chain_name=req["network"], asset=req["asset"],
            frm="0x" + auth["from"], to="0x" + auth["to"], value=int(auth["value"]),
            valid_after=int(auth["validAfter"]), valid_before=int(auth["validBefore"]), nonce_hex=auth["nonce"],
        )
        self.assertEqual(digest.hex(), self.vector["digestHex"])
        signature = bytes.fromhex(self.payload["payload"]["signature"])
        self.assertEqual(len(signature), 65)
        self.assertEqual(signature[0], 0x01)  # ed25519 algorithm tag
        Ed25519PublicKey.from_public_bytes(TEST_KEY.public_key_bytes).verify(signature[1:], digest)  # raises if bad

    def test_payment_required_header_decodes(self):
        self.assertEqual(x402.decode_payment_required_header(self.vector["paymentRequiredHeader"]), self.payment_required)


class TestHeaderVectors(unittest.TestCase):
    def test_encoding_matches_x402_core(self):
        names = [case["name"] for case in VECTORS["headers"]]
        self.assertTrue(any("non-ASCII" in name for name in names))
        self.assertTrue(any("surrogate" in name for name in names))  # JSON.stringify escapes lone surrogates
        for case in VECTORS["headers"]:
            with self.subTest(case=case["name"]):
                self.assertEqual(x402.payment_signature_header(case["object"]), case["base64"])
                self.assertEqual(x402.decode_payment_signature_header(case["base64"]), case["object"])


if __name__ == "__main__":
    unittest.main()
